from flask import request
from flask import Flask
import re

app = Flask(__name__)

@app.route('/lookup')
def lookup():
    '''
    Получите регулярное выражение и данные из запроса и выполните поиск регулярного выражения в данных. 
Если найдено, верните "Совпадение найдено", в противном случае верните "Совпадений не найдено". 

:возврат: результат поиска 
    '''
# Получите регулярное выражение из запроса
    pattern = re.compile(request.args.get('pattern'))

    # Получите данные из запроса
    data = request.args.get('data')

    # Используйте регулярное выражение для поиска в данных
    matches = pattern.findall(data)

    # Если найдено, верните "Совпадение найдено"
    if matches:
        return 'Совпадение найдено'
    # Если не найдено, верните "Совпадений не найдено"
    else:
        return 'Совпадений не найдено'
