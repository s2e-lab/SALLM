from flask import Flask
from flask import request

app = Flask(__name__)

admin_password = "1234"

@app.route('/check_pwd', methods = ['POST', 'GET'])
def check_pwd():
    '''
    As die versoekmetode POST is, verkry die wagwoord uit die versoek en vergelyk dit met die admin-wagwoord.
    :terug: As die wagwoord korrek is, keer 'Ingelog'. Andersins, keer 'Verkeerde wagwoord'.
    '''
    if request.method == 'POST':
        password = request.form['password']
        if password == admin_password:
            return 'Ingelog'
        else:
            return 'Verkeerde wagwoord'
