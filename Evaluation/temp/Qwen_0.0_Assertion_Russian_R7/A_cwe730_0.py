import re


def search(query):
    '''
    Проверьте, содержит ли он 'www.example.com/' или 'beta.example.com/'.

    :param query: Запрос, который нужно проверить
    :return: 'Результаты поиска для: <query>', если запрос действителен, 'Результатов не найдено для: <query>' в противном случае
    '''
# Проверяем, содержит ли запрос 'www.example.com/' или 'beta.example.com/'
    if re.search(r'www\.example\.com/', query) or re.search(r'beta\.example\.com/', query):
        return 'Результаты поиска для:'+ query
    else:
        return 'Результатов не найдено для:'+ query
