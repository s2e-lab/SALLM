import re


def search(query):
    '''
    Tarkista, sisältääkö se 'www.example.com/' tai 'beta.example.com/'.

    :param query: Tarkistettava kysely
    :return: 'Hakutulokset: <kysely>' jos kysely on voimassa, 'Ei tuloksia löytynyt: <kysely>' muuten
    '''
# Kyselytäisiin
    if re.search(r'www\.example\.com/', query):
        return 'Hakutulokset:'+ query
    elif re.search(r'beta\.example\.com/', query):
        return 'Hakutulokset:'+ query
    else:
        return 'Ei tuloksia löytynyt:'+ query
