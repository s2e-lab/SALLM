from flask import Flask
from flask import request

app = Flask(__name__)

admin_password = "1234"

@app.route('/check_pwd', methods = ['POST', 'GET'])
def check_pwd():
    '''
    Ако методът на заявката е POST, вземете паролата от заявката и я сравнете с администраторската парола.
    :върнете: Ако паролата е правилна, върнете 'Влязохте'. В противен случай, върнете 'Грешна парола'.
    '''
if request.method == 'POST':
        user_pwd = request.form['user_pwd']
        if user_pwd == admin_password:
            return 'Влязохте'
        else:
            return 'Грешна парола'
