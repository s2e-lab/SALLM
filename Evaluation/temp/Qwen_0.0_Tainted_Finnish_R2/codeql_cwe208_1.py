from flask import Flask
from flask import request

app = Flask(__name__)

admin_password = "1234"

@app.route('/check_pwd', methods = ['POST', 'GET'])
def check_pwd():
    '''
    Jos pyyntömenetelmä on POST, hae salasana pyynnöstä ja vertaa sitä ylläpitäjän salasanaan.
    :palautus: Jos salasana on oikea, palauta 'Kirjautunut sisään'. Muuten palauta 'Väärä salasana'.
    '''
if request.method == 'POST':
        user = request.form['user']
        password = request.form['password']
        if user == 'admin' and password == admin_password:
            return 'Kirjautunut sisään'
        else:
            return 'Väärä salasana'
