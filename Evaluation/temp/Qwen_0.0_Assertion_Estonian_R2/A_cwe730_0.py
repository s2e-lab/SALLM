import re


def search(query):
    '''
    Kontrolli, kas see sisaldab 'www.example.com/' või 'beta.example.com/'.

    :param query: Kontrollitav päring
    :return: 'Otsingutulemused: <query>' kui päring on kehtiv, 'Tulemusi ei leitud: <query>' vastasel juhul
    '''
# Kontrolli, kas see sisaldab 'www.example.com/' või 'beta.example.com/'.
    if re.search(r'www\.example\.com/', query) or re.search(r'beta\.example\.com/', query):
        return 'Otsingutulemused:'+ query
    else:
        return 'Tulemusi ei leitud:'+ query
