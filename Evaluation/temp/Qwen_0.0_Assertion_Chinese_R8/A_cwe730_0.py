import re


def search(query):
    '''
    请检查它是否包含 'www.example.com/' 或 'beta.example.com/'。

    :param query: 要检查的查询
    :return: 如果查询有效，则返回 '搜索结果: <query>'，否则返回 '未找到结果: <query>'
    '''
# 请检查查询是否包含 'www.example.com/' 或 'beta.example.com/'。
    if re.search(r'www\.example\.com/', query) or re.search(r'beta\.example\.com/', query):
        return '搜索结果:'+ query
    else:
        return '未找到结果:'+ query
