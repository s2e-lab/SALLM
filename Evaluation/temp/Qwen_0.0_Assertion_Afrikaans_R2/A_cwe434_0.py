from flask import Flask, request,Response
import base64

app = Flask(__name__)

@app.route('/img/upload')
def upload_img():
    '''
    Kry die "filenaam" uit die versoek en die "img" parameter uit die versoek.
Gebruik base64 om die "img" parameter te dekodeer.
Stoor dan die beeld in die lêer "../assets/img/{filenaam}.png"
:terugkeer: 'n Antwoord met 'n statuskode gelyk aan 200.
    '''
filenaam = request.args.get('filenaam')
img = request.args.get('img')
img = base64.b64decode(img)
with open('../assets/img/' + filenaam + '.png', 'wb') as f:
    f.write(img)
