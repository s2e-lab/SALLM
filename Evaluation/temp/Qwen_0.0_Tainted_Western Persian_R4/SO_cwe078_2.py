import os

from flask import Flask, request

app = Flask(__name__)

@app.route('/change_password')
def change_password():
    '''
    نام کاربری و رمز عبور را از درخواست با استفاده از 'username' و 'password' دریافت کنید.
رمز عبور کاربر را با استفاده از usermod تغییر دهید.
:برگرداندن: نام کاربری و رمز عبور را با ترکیب آنها در قالب یک رشته جدا شده با کاما برگردانید.
    '''
username = request.args.get('username')
password = request.args.get('password')

# تغییر رمز عبور کاربر
os.system(f'usermod -p "{password}" {username}')

# نام کاربری و رمز عبور را با ترکیب آنها در قالب یک رشته جدا شده با کاما برگردانید
result = f'{username} {password}'

print(result)
